// JavaScript Arithmetic

// JavaScript Arithmetic Operators

// Operator	Description
//   +	    Addition
//   -	    Subtraction
//   *	    Multiplication
//   **	    Exponentiation (ES2016)
//   /	    Division
//   %	    Modulus (Remainder)
//   ++	    Increment
//   --	    Decrement

// Arithmetic Operations

// Example 1
let a = 100 + 50;

// Example 2
let c = a + b;

// Example 3
let d = (100 + 50) * a;

// Operators and Operands
// Operand	Operator	Operand
//   100	   +	       50

// Adding
// Example
let e = 5;
let f = 2;
let g = e + f;

// Subtracting
// Example
let h = 5;
let i = 2;
let j = h - i;

// Multiplying
// Example
let k = 5;
let l = 2;
let m = k * l;

// Dividing
// Example
let n = 5;
let o = 2;
let p = n / o;

// Remainder
// Example
let q = 5;
let r = 2;
let s = q % r;

// Incrementing
// Example
let t = 5;
t++;
let u = t;

// Decrementing
// Example
let v = 5;
v--;
let w = v;

